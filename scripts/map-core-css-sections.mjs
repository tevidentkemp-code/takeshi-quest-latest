import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import postcss from 'postcss';

const root = process.cwd();
const sourceFile = 'src/legacy/styles/inline-002.css';
const sourcePath = path.join(root, sourceFile);
const manifestPath = path.join(root, 'src', 'styles', 'core-css-section-manifest.json');
const reportPath = path.join(root, 'docs', 'architecture', 'CORE_CSS_SECTION_MAP.md');

if (!fs.existsSync(sourcePath)) fail(`Missing core stylesheet: ${sourceFile}`);
const css = fs.readFileSync(sourcePath, 'utf8');
const parsed = postcss.parse(css, { from: sourceFile });
const lineStarts = buildLineStarts(css);

const markers = [];
for (const node of parsed.nodes || []) {
  if (node.type !== 'comment') continue;
  const match = String(node.text || '').match(/@CSS:([A-Za-z0-9_-]+)/);
  if (!match) continue;
  const line = node.source?.start?.line;
  const column = node.source?.start?.column;
  if (!Number.isInteger(line) || !Number.isInteger(column)) {
    fail(`Marker ${match[1]} has no stable PostCSS source position`);
  }
  const offset = offsetFromLineColumn(line, column, lineStarts);
  markers.push({ name: match[1], offset, line });
}

assert(markers.length > 0, 'No top-level @CSS:* markers found in core stylesheet');
for (let i = 1; i < markers.length; i += 1) {
  assert(markers[i].offset > markers[i - 1].offset, `Non-increasing marker offset at ${markers[i].name}`);
}

const sections = [];
if (markers[0].offset > 0) {
  sections.push(buildSection('PRELUDE', 0, markers[0].offset, 1));
}
for (let i = 0; i < markers.length; i += 1) {
  const start = markers[i].offset;
  const end = i + 1 < markers.length ? markers[i + 1].offset : css.length;
  sections.push(buildSection(markers[i].name, start, end, markers[i].line));
}

const rebuilt = sections.map(section => section.content).join('');
assert(rebuilt === css, 'Core CSS section slices do not reconstruct the source byte-for-byte');

const publicSections = sections.map(({ content, ...section }) => section);
const manifest = {
  schemaVersion: 1,
  generatedBy: 'scripts/map-core-css-sections.mjs',
  stage: 'mapping-only',
  runtimeChanged: false,
  source: sourceFile,
  sourceBytes: Buffer.byteLength(css),
  sourceSha256: sha256(css),
  markerConvention: '@CSS:* top-level PostCSS comments',
  sectionCount: publicSections.length,
  sections: publicSections
};

fs.mkdirSync(path.dirname(manifestPath), { recursive: true });
fs.mkdirSync(path.dirname(reportPath), { recursive: true });
fs.writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
fs.writeFileSync(reportPath, buildReport(manifest), 'utf8');
console.log(`SC-031 core CSS map PASS: ${manifest.sectionCount} exact top-level sections mapped across ${manifest.sourceBytes} bytes.`);

function buildSection(name, startOffset, endOffset, startLine) {
  const content = css.slice(startOffset, endOffset);
  assert(content.length > 0, `Empty core CSS section: ${name}`);
  const tree = postcss.parse(content, { from: `${sourceFile}#${name}` });
  let rules = 0;
  let declarations = 0;
  let important = 0;
  tree.walkRules(() => { rules += 1; });
  tree.walkDecls(decl => {
    declarations += 1;
    if (decl.important) important += 1;
  });
  const endLine = startLine + (content.match(/\n/g)?.length || 0);
  return {
    order: sections.length + 1,
    marker: name,
    slug: slugify(name),
    startOffset,
    endOffset,
    startLine,
    endLine,
    bytes: Buffer.byteLength(content),
    sha256: sha256(content),
    rules,
    declarations,
    importantDeclarations: important,
    content
  };
}

function buildLineStarts(value) {
  const starts = [0];
  for (let i = 0; i < value.length; i += 1) {
    if (value[i] === '\n') starts.push(i + 1);
  }
  return starts;
}

function offsetFromLineColumn(line, column, starts) {
  assert(line >= 1 && line <= starts.length, `Invalid line ${line}`);
  assert(column >= 1, `Invalid column ${column}`);
  return starts[line - 1] + column - 1;
}

function buildReport(manifest) {
  const rows = manifest.sections.map(section =>
    `| ${section.order} | \`${section.marker}\` | ${section.startLine}-${section.endLine} | ${section.bytes.toLocaleString('en-GB')} | ${section.rules} | ${section.declarations} | ${section.importantDeclarations} | \`${section.sha256.slice(0, 12)}…\` |`
  ).join('\n');
  return `# SC-031 Core CSS Section Map\n\n` +
    `Generated by \`scripts/map-core-css-sections.mjs\`. This is evidence only; it does not change runtime CSS.\n\n` +
    `- Source: \`${manifest.source}\`\n` +
    `- Source bytes: ${manifest.sourceBytes.toLocaleString('en-GB')}\n` +
    `- Source SHA-256: \`${manifest.sourceSha256}\`\n` +
    `- Top-level sections: ${manifest.sectionCount}\n` +
    `- Boundary rule: actual top-level PostCSS comments using \`${manifest.markerConvention}\`\n` +
    `- Reconstruction: exact source concatenation required\n\n` +
    `| # | Marker | Lines | Bytes | Rules | Declarations | !important | SHA-256 |\n` +
    `|---:|---|---:|---:|---:|---:|---:|---|\n${rows}\n\n` +
    `## Migration rule\n\nOnly sections proven independently parseable and exactly reconstructable may be promoted. Marker names are source evidence, not product authority. Cascade order must remain identical until a separately tested cleanup removes historical overrides.\n`;
}

function slugify(value) {
  return String(value).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'section';
}

function sha256(value) {
  return crypto.createHash('sha256').update(value).digest('hex');
}

function assert(condition, message) {
  if (!condition) fail(message);
}

function fail(message) {
  console.error(`SC-031 core CSS map FAIL: ${message}`);
  process.exit(1);
}
